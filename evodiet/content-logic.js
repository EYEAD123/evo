function switchSection(id) {
    document.querySelectorAll('.content-section').forEach(s => s.classList.remove('active'));
    document.getElementById(id).classList.add('active');
    document.querySelectorAll('.island-item').forEach(i => {
        i.classList.toggle('active', i.dataset.target === id);
    });
    // إذا دخل قسم التمارين، شغل الحالة الافتراضية
    if (id === 'workouts') selectEnv(currentEnv);
}

// --- 4. منطق التمارين ---
function selectEnv(env) {
    currentEnv = env;

    // إزالة اللون البرتقالي من كل أزرار البيئة
    document.querySelectorAll('.env-btn').forEach(btn => btn.classList.remove('active'));

    // إضافة اللون للزر المختار
    document.querySelectorAll('.env-btn').forEach(btn => {
        if (btn.getAttribute('onclick') && btn.getAttribute('onclick').includes(`'${env}'`)) {
            btn.classList.add('active');
        }
    });

const tabs = document.getElementById('muscleTabs');
const layout = document.querySelector('.workout-layout');

if (env === 'cardio') {
    if (tabs) tabs.style.display = 'none';
    if (layout) layout.style.gridTemplateColumns = '1fr';
    displayCardio();
} else {
    if (tabs) tabs.style.display = '';
    if (layout) layout.style.gridTemplateColumns = '';
    currentMuscle = 'chest';
    filterWorkouts('chest');
}
}











// ✅ تعريف واحد فقط لـ filterWorkouts — يشتغل مع home/gym/cali
function filterWorkouts(muscle, clickedBtn) {
    currentMuscle = muscle;
    const display = document.getElementById('workoutDisplay');
    const envData = workoutData[currentEnv];

    if (!envData) return;

    const data = envData[muscle] || [];

    display.innerHTML = data.length > 0
        ? data.map(ex => `
            <div class="glass-card workout-card">
                <div class="card-head">
                    <h4>${ex.name}</h4>
                    <span class="tag">${ex.sets || 'تمرين'}</span>
                </div>
                <div class="workout-details" style="margin-top:10px;">
                    <p style="font-size:0.9rem; color:#ff6c00;"><b>الأداة:</b> ${ex.tool}</p>
                    <p style="font-size:0.85rem; color:#ccc;">${ex.desc}</p>
                </div>
            </div>
        `).join('')
        : `<p style="color:#888; text-align:center; padding:20px;">لا توجد تمارين لهذه العضلة في هذه البيئة.</p>`;

    // ✅ تحديث الـ active على tab buttons بشكل آمن
    document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
    if (clickedBtn) {
        clickedBtn.classList.add('active');
    } else {
        // تفعيل الزر المطابق للعضلة الحالية
        document.querySelectorAll('.tab-btn').forEach(b => {
            if (b.getAttribute('onclick') && b.getAttribute('onclick').includes(`'${muscle}'`)) {
                b.classList.add('active');
            }
        });
    }
}












