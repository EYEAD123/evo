// --- 3. معالجة البيانات والحسابات ---
function processData() {
    const w    = parseFloat(document.getElementById('weight').value);
    const h    = parseFloat(document.getElementById('height').value);
    const a    = parseFloat(document.getElementById('age').value);
    const gen  = document.getElementById('gender').value;
    const act  = parseFloat(document.getElementById('activity').value);
    const goal = document.getElementById('goal').value;

    if (!w || !h || !a) { alert("أكمل البيانات الأساسية أولاً"); return; }

    // ===== المدخلات الاختيارية =====
    const bfInput = parseFloat(document.getElementById('bodyfat').value);
    const smInput = parseFloat(document.getElementById('musclemass').value);

    // ===== حساب نسبة الدهون =====
    let bf = null;
    let bfSource = '';

    if (!isNaN(bfInput) && bfInput > 3 && bfInput < 65) {
        // الأولوية: لو دخل النسبة بنفسه
        bf = bfInput;
        bfSource = 'مدخلة يدوياً';

    } else if (gen === 'male') {
        const waist = parseFloat(document.getElementById('m_waist').value);
        const neck  = parseFloat(document.getElementById('m_neck').value);
        if (!isNaN(waist) && !isNaN(neck) && waist > neck) {
            bf = 495 / (1.0324 - 0.19077 * Math.log10(waist - neck) + 0.15456 * Math.log10(h)) - 450;
            bfSource = 'Navy Method';
        }

    } else if (gen === 'female') {
        const waist = parseFloat(document.getElementById('f_waist').value);
        const hips  = parseFloat(document.getElementById('f_hips').value);
        const neck  = parseFloat(document.getElementById('f_neck').value);
        if (!isNaN(waist) && !isNaN(hips) && !isNaN(neck)) {
            bf = 495 / (1.29579 - 0.35004 * Math.log10(waist + hips - neck) + 0.22100 * Math.log10(h)) - 450;
            bfSource = 'Navy Method';
        }
    }

    // تحقق من المنطقية
    if (bf !== null) {
        bf = parseFloat(bf.toFixed(1));
        if (bf < 3 || bf > 65) bf = null;
    }



    
// ===== حساب BMR =====
    let bmr;

    if (!isNaN(smInput) && smInput > 20 && smInput < 70 && bf !== null) {
        // الأدق: عضلات + دهون معاً — بنحسب الـ lean mass بدقة أعلى
        const fatMassKg    = w * (bf / 100);
        const muscleMassKg = w * (smInput / 100);
        const lbm          = w - fatMassKg;
        // weighted average بين Cunningham و Katch-McArdle
        const bmrCunn  = 500 + (22 * muscleMassKg);
        const bmrKatch = 370 + (21.6 * lbm);
        bmr = (bmrCunn + bmrKatch) / 2;

    } else if (!isNaN(smInput) && smInput > 20 && smInput < 70) {
        // Cunningham — عنده نسبة عضلات بس
        const muscleMassKg = w * (smInput / 100);
        bmr = 500 + (22 * muscleMassKg);

    } else if (bf !== null) {
        // Katch-McArdle — عنده نسبة دهون بس
        const lbm = w * (1 - bf / 100);
        bmr = 370 + (21.6 * lbm);

    } else {
        // Mifflin-St Jeor — الافتراضي
        bmr = (10 * w) + (6.25 * h) - (5 * a);
        bmr = (gen === 'male') ? bmr + 5 : bmr - 161;
    }



    // ===== TDEE + الهدف =====
    let tdee = bmr * act;
    if      (goal === 'lose')     tdee -= 500;
    else if (goal === 'gain')     tdee += 500;
    else if (goal === 'maintain') tdee -= 200;

    const finalCalories = Math.round(tdee);
    const water = (w * 0.035).toFixed(1);





    // ===== عرض النتايج =====
    document.getElementById('resCalories').innerText = finalCalories;
    document.getElementById('resWater').innerText = water;
    document.getElementById('resBF').innerText = bf !== null
        ? bf + '% (' + bfSource + ')'
        : '— (أدخل المقاسات أو النسبة)';

    generateMeals(finalCalories, water);
    document.getElementById('mealLink').classList.remove('disabled');
    switchSection('meals');
}

