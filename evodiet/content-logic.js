// --- 4. توليد الوجبات وتوزيع السعرات ---
function generateMeals(calories, water) {
    const container = document.getElementById('mealsContainer');
    const goal = document.getElementById('goal').value;
    container.innerHTML = "";

    // بطاقة الترطيب
    container.innerHTML += `
        <div class="meal-card" style="border-right: 4px solid #00ccff; width: 100%;">
            <div class="card-head">
                <h4>ترطيب الجسم</h4>
                <span class="tag">أساسي</span>
            </div>
            <p>يجب شرب ${water} لتر ماء يومياً لضمان الحرق العالي.</p>
            <div class="card-foot"><i class="fas fa-tint"></i> يومياً</div>
        </div>
    `;

    // بطاقة نصيحة الهدف
    const goalTips = {
        lose: { icon: '🔥', title: 'نصيحة التنحيف', tip: 'ركّز على البروتين العالي والكارب المنخفض. تجنب السكريات والأكل المعالج. وزّع وجباتك على 4-5 مرات يومياً.' },
        gain: { icon: '💪', title: 'نصيحة البلكنج', tip: 'اهتم بزيادة الكارب والبروتين معاً. كُل كل 3 ساعات. أضف وجبة قبل النوم غنية بالبيض أو الجبن القريش.' },
        maintain: { icon: '⚡', title: 'نصيحة التنشيف', tip: 'احتفظ بالكارب حول التمرين فقط. ارفع البروتين إلى 2.2 جرام لكل كيلو. الكارب في الصباح وبعد التمرين.' }
    };
    const tip = goalTips[goal];
    container.innerHTML += `
        <div class="meal-card" style="border-right: 4px solid var(--primary-orange); width: 100%;">
            <div class="card-head">
                <h4>${tip.icon} ${tip.title}</h4>
            </div>
            <p style="color:#aaa; font-size:0.9rem; line-height:1.7;">${tip.tip}</p>
        </div>
    `;

    // توزيع الوجبات حسب الهدف
    let remaining = calories;

    if (goal === 'gain') {
        // البلكنج: وجبات أكبر
        while (remaining >= 250) {
            if (remaining >= 600) {
                container.innerHTML += createMealCard('main', 600);
                remaining -= 600;
            } else if (remaining >= 400) {
                container.innerHTML += createMealCard('main', 400);
                remaining -= 400;
            } else {
                container.innerHTML += createMealCard('snack', 250);
                remaining -= 250;
            }
        }
    } else {
        // خسارة وزن / تنشيف: وجبات عادية
        while (remaining >= 250) {
            if (remaining >= 500) {
                container.innerHTML += createMealCard('main', 500);
                remaining -= 500;
            } else {
                container.innerHTML += createMealCard('snack', 250);
                remaining -= 250;
            }
        }
    }
}

// بناء كارت وجبة تفاعلي
function createMealCard(type, cal) {
    const meals = foodBank[type];
    const meal = meals[Math.floor(Math.random() * meals.length)];
    const vitsHTML = meal.vits.map(v => `<span class="vit-tag" style="background: rgba(255,108,0,0.1); padding: 2px 8px; border-radius: 4px; font-size: 0.75rem; margin-left: 5px;">${v}</span>`).join('');

    return `
        <div class="meal-card" data-type="${type}" data-cal="${cal}" style="width: 100%; max-width: 100%;">
            <div class="card-head">
                <div>
                    <h4>${meal.title}</h4>
                    <p class="meal-prep" style="font-size: 0.9rem; color: #888;">${meal.prep}</p>
                </div>
                <span class="tag">${cal} سعرة</span>
            </div>
            
            <div class="meal-details" style="margin: 15px 0; padding: 15px 0; border-top: 1px solid rgba(255,255,255,0.05); border-bottom: 1px solid rgba(255,255,255,0.05);">
                <div style="margin-bottom: 10px;">
                    <strong class="orange" style="font-size: 0.85rem; display: block; margin-bottom: 5px;"><i class="fas fa-utensils"></i> طريقة التحضير:</strong>
                    <p class="meal-steps" style="font-size: 0.85rem; color: #ccc; line-height: 1.5;">${meal.steps}</p>
                </div>
                <div>
                    <strong class="orange" style="font-size: 0.85rem; display: block; margin-bottom: 5px;"><i class="fas fa-capsules"></i> المعادن والفيتامينات:</strong>
                    <div class="meal-vits">${vitsHTML}</div>
                </div>
            </div>

            <div class="macros">
                <span>بروتين: <b class="p-val">${meal.p}</b></span> | <span>كارب: <b class="c-val">${meal.c}</b></span> | <span>دهون: <b class="f-val">${meal.f}</b></span>
            </div>
            <button class="change-meal-btn" onclick="shuffleMeal(this)">
                <i class="fas fa-sync-alt"></i> تغيير الوجبة
            </button>
        </div>
    `;
}

// وظيفة تبديل الوجبة
function shuffleMeal(btn) {
    const card = btn.closest('.meal-card');
    const type = card.dataset.type;
    const meals = foodBank[type];
    const newMeal = meals[Math.floor(Math.random() * meals.length)];

    card.style.opacity = '0.5';
    card.style.transform = 'scale(0.98)';

    setTimeout(() => {
        card.querySelector('h4').innerText = newMeal.title;
        card.querySelector('.meal-prep').innerText = newMeal.prep;
        card.querySelector('.meal-steps').innerText = newMeal.steps;
        card.querySelector('.meal-vits').innerHTML = newMeal.vits.map(v => `<span class="vit-tag" style="background: rgba(255,108,0,0.1); padding: 2px 8px; border-radius: 4px; font-size: 0.75rem; margin-left: 5px;">${v}</span>`).join('');
        card.querySelector('.p-val').innerText = newMeal.p;
        card.querySelector('.c-val').innerText = newMeal.c;
        card.querySelector('.f-val').innerText = newMeal.f;

        card.style.opacity = '1';
        card.style.transform = 'scale(1)';
    }, 200);
}

